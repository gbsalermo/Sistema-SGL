-- Catalogo de bolsas da Unidade, sem dependencia de TipoBolsa (enum legado).
-- A V49 de produtos permanece intacta.
CREATE TABLE bolsas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    unidade_id BIGINT NOT NULL,
    nome VARCHAR(150) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_bolsas_public_id UNIQUE (public_id),
    CONSTRAINT fk_bolsas_unidade FOREIGN KEY (unidade_id) REFERENCES unidades(id)
);

CREATE UNIQUE INDEX uk_bolsas_unidade_nome_ci ON bolsas(unidade_id, lower(nome));
CREATE INDEX idx_bolsas_unidade_ativo ON bolsas(unidade_id, ativo);

-- Vínculos legados continuam com tipo_bolsa preenchido. O catálogo é alternativa,
-- não especialização nem subtipo do enum.
ALTER TABLE vinculos_estagio
    ALTER COLUMN tipo_bolsa DROP NOT NULL,
    ADD COLUMN bolsa_id BIGINT,
    ADD COLUMN bolsa_nome VARCHAR(150);

ALTER TABLE vinculos_estagio
    ADD CONSTRAINT fk_vinculos_estagio_bolsa
    FOREIGN KEY (bolsa_id) REFERENCES bolsas(id);

-- Cada ocorrência aponta a exatamente uma origem, sem "tipo base" fictício.
ALTER TABLE vinculos_estagio
    ADD CONSTRAINT ck_vinculos_estagio_origem_bolsa
    CHECK (
        (tipo_bolsa IS NOT NULL AND bolsa_id IS NULL)
        OR
        (tipo_bolsa IS NULL AND bolsa_id IS NOT NULL)
    );

CREATE INDEX idx_vinculos_estagio_bolsa ON vinculos_estagio(bolsa_id);

-- Estagiarios.tipo_bolsa é coluna legada informativa. Para bolsa nova sem enum,
-- ficará NULL; a origem correta fica no VinculoEstagio atual.
ALTER TABLE estagiarios ALTER COLUMN tipo_bolsa DROP NOT NULL;
