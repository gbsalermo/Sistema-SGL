-- Catalogo configuravel de modalidades de bolsa, sem migrar o enum/contrato legado.
CREATE TABLE modalidades_bolsa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    unidade_id BIGINT NOT NULL,
    nome VARCHAR(150) NOT NULL,
    tipo_base VARCHAR(40) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_modalidades_bolsa_public_id UNIQUE (public_id),
    CONSTRAINT fk_modalidades_bolsa_unidade FOREIGN KEY (unidade_id) REFERENCES unidades(id)
);

-- Evita duplicidades por caixa de texto dentro de cada Unidade.
CREATE UNIQUE INDEX uk_modalidades_bolsa_unidade_nome_ci
    ON modalidades_bolsa(unidade_id, lower(nome));
CREATE INDEX idx_modalidades_bolsa_unidade_ativo
    ON modalidades_bolsa(unidade_id, ativo);

-- Associacao opcional e nome historico: vinculos antigos continuam validos.
ALTER TABLE vinculos_estagio
    ADD COLUMN modalidade_bolsa_id BIGINT,
    ADD COLUMN modalidade_bolsa_nome VARCHAR(150);

ALTER TABLE vinculos_estagio
    ADD CONSTRAINT fk_vinculos_estagio_modalidade_bolsa
    FOREIGN KEY (modalidade_bolsa_id) REFERENCES modalidades_bolsa(id);

CREATE INDEX idx_vinculos_estagio_modalidade_bolsa
    ON vinculos_estagio(modalidade_bolsa_id);
