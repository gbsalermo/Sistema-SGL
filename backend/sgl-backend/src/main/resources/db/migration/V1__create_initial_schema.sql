CREATE TABLE unidades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    sigla VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE produtos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    descricao VARCHAR(255),
    codigo_referencia VARCHAR(255) UNIQUE,

    unidade_medida VARCHAR(255) NOT NULL,
    localizacao_fisica VARCHAR(255),

    risco VARCHAR(255) NOT NULL,
    tipo_risco VARCHAR(255),
    descricao_risco VARCHAR(255),

    perecivel BOOLEAN NOT NULL,
    tipo_perecivel VARCHAR(255),

    condicoes_armazenamento VARCHAR(255),
    unidade_armazenamento VARCHAR(255),

    ativo BOOLEAN NOT NULL
);

CREATE TABLE laboratorios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    unidade_id BIGINT NOT NULL,

    nome VARCHAR(255) NOT NULL,
    descricao VARCHAR(255),

    responsavel_id BIGINT,

    ativo BOOLEAN NOT NULL,

    CONSTRAINT fk_laboratorio_unidade
        FOREIGN KEY (unidade_id)
        REFERENCES unidades(id)
);

CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    perfil VARCHAR(255) NOT NULL,

    unidade_id BIGINT,
    laboratorio_id BIGINT,

    ativo BOOLEAN NOT NULL,

    CONSTRAINT fk_usuario_unidade
        FOREIGN KEY (unidade_id)
        REFERENCES unidades(id),

    CONSTRAINT fk_usuario_laboratorio
        FOREIGN KEY (laboratorio_id)
        REFERENCES laboratorios(id)
);

